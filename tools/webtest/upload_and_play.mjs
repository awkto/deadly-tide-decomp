import puppeteer from "puppeteer";
const [file, seg, out] = process.argv.slice(2);
const b = await puppeteer.launch({headless:true, userDataDir:"/root/wasm-test/profile", args:["--no-sandbox","--autoplay-policy=no-user-gesture-required","--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
const p = await b.newPage();
const errs=[];
p.on("console", m=>{ console.log("[console."+m.type()+"]", m.text()); if(m.type()==="error") errs.push(m.text()); });
p.on("pageerror", e=>{ console.log("[pageerror]", e.message); errs.push(e.message); });
await p.goto("http://localhost:8099/index.html");
await p.waitForFunction("runtimeReady", {timeout:30000});
const inp = await p.$("#files");
await inp.uploadFile(file);
await p.waitForFunction("document.querySelectorAll(\"#seg option\").length>0", {timeout:60000});
await p.select("#seg", seg);
await p.click("#play");
await new Promise(r=>setTimeout(r,5000));
const el = await p.$("#canvas"); await el.screenshot({path:out+"_a.png"});
await new Promise(r=>setTimeout(r,4000));
await el.screenshot({path:out+"_b.png"});
console.log("ERRORS:", errs.length, JSON.stringify(errs));
await b.close();
